import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const require=createRequire(import.meta.url);
const {chromium}=require('C:/Users/tjqmf/AppData/Local/npm-cache/_npx/31e32ef8478fbf80/node_modules/playwright');
const base=JSON.parse(fs.readFileSync(new URL('../.data/server.json',import.meta.url))).url;
const sample=new URL('../output/playwright/wheel-fixture.pdf',import.meta.url);
fs.mkdirSync(new URL('../output/playwright/',import.meta.url),{recursive:true});
execFileSync('python',['-c',"import fitz,sys; d=fitz.open(); [d.new_page().insert_text((72,72),f'Page {i}') for i in range(1,9)]; d.save(sys.argv[1])",fileURLToPath(sample)]);
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1400,height:900}});
  const errors=[];
  // Exercise the compatibility download path; native-picker saving has separate tests.
  await page.addInitScript(()=>{window.showSaveFilePicker=undefined;});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base);
  await page.locator('#fileInput').setInputFiles(fileURLToPath(sample));
  await page.locator('#reader').waitFor({state:'visible',timeout:30000});
  const number=page.locator('#pageNumber');
  await page.waitForFunction(()=>document.querySelector('#pageNumber').value==='1');
  const stage=page.locator('#readerStage');
  await stage.hover();
  await page.mouse.wheel(0,120);
  await page.waitForFunction(()=>Number(document.querySelector('#pageNumber').value)>1);
  const afterDown=Number(await number.inputValue());
  await page.waitForTimeout(850);
  await page.mouse.wheel(0,-120);
  await page.waitForFunction(()=>document.querySelector('#pageNumber').value==='1');
  await page.waitForTimeout(850);
  for(let i=0;i<5;i++)await page.mouse.wheel(0,120);
  await page.waitForTimeout(900);
  assert.equal(Number(await number.inputValue()),afterDown,'rapid wheel events must turn one page');
  await page.locator('#zoomInButton').click();
  await page.waitForTimeout(850);
  await stage.hover();
  const beforePan=await number.inputValue();
  await page.mouse.wheel(0,120);
  await page.waitForTimeout(800);
  assert.equal(await number.inputValue(),beforePan,'wheel at 125% must pan, not turn');
  const [download]=await Promise.all([page.waitForEvent('download',{timeout:30000}),page.locator('#exportBook').click()]);
  const zipPath=fileURLToPath(new URL('../output/playwright/wheel-export.zip',import.meta.url));
  await download.saveAs(zipPath);
  execFileSync('python',['-c',"import sys,zipfile; from PIL import Image; z=zipfile.ZipFile(sys.argv[1]); s=z.read('js/viewer.js').decode('utf-8'); assert 'wheelDistance' in s; pages=[p for p in z.namelist() if p.startswith('pages/')]; assert len(pages)==8 and all(p.endswith('.webp') for p in pages); assert all(Image.open(z.open(p)).format=='WEBP' for p in pages)",zipPath]);
  assert.deepEqual(errors,[]);
  console.log(`Wheel test passed: down 1→${afterDown}, up ${afterDown}→1, rapid wheel one turn, zoomed wheel pans, ZIP contains 8 valid WebP pages`);
} finally {await browser.close();}
